def run_tests(repo, tests):
    """(passed, the failing tests' names)."""
    failed = []
    py = [t for t in tests if t != "node"]
    if py:
        r = subprocess.run([sys.executable, "-B", "-m", "unittest", *py], cwd=repo, capture_output=True, text=True, timeout=900)
        if r.returncode != 0:
            failed += [line.split(" ", 2)[1] for line in r.stderr.splitlines()
                       if line.startswith(("FAIL: ", "ERROR: "))] or ["unittest exit %d" % r.returncode]
    if "node" in tests:
        r = subprocess.run(["node", "--test", "tests/model.test.cjs"], cwd=repo, capture_output=True, text=True, timeout=300)
        if r.returncode != 0:
            failed += ["node: " + line.strip()[2:].strip() for line in r.stdout.splitlines() if line.strip().startswith("✖ ")][:1] or ["node"]
    return not failed, failed


def main():
    src = os.path.abspath(sys.argv[1])
    confirm = "--confirm" in sys.argv[2:]
    only = set(a for a in sys.argv[2:] if a != "--confirm")
    unknown = only - {m[0] for m in MUTATIONS}
    if unknown:  # (a misspelt name used to run nothing and pass)
        sys.exit("no such mutation: " + "; ".join(sorted(unknown)))
    work = tempfile.mkdtemp(prefix="legato-mut-", dir=None if len(tempfile.gettempdir()) <= 40 else "/tmp")
    repo = os.path.join(work, "repo")
    shutil.copytree(src, repo, ignore=shutil.ignore_patterns(".git", "__pycache__", "media", "branding"))
    killed = survived = stale = skipped = flaky = 0
    baseline = {}
    for name, path, old, new, tests in MUTATIONS:
        if only and name not in only:
            continue
        key = tuple(tests)
        if key not in baseline:
            # A red baseline would count every mutant as killed.
            baseline[key] = run_tests(repo, tests)
            if not baseline[key][0]:
                print("BASELINE RED  %s: %s" % (", ".join(tests), baseline[key][1]))
        if not baseline[key][0]:
            skipped += 1; print("SKIP  %-40s (its tests fail unmutated)" % name); continue
        full = os.path.join(repo, path)
        original = open(full, encoding="utf-8").read()
        count = original.count(old)
        if count != 1:
            stale += 1; print("STALE  %-40s (pattern found %d times: fix the mutation)" % (name, count)); continue
        open(full, "w", encoding="utf-8").write(original.replace(old, new))
        try:
            passed, failing = run_tests(repo, tests)
        finally:
            open(full, "w", encoding="utf-8").write(original)
        if not passed and confirm and not run_tests(repo, tests)[0]:
            # (Strict review 22, fit F5: under parallel load a timing failure
            # "killed" two mutants that survive alone.)
            flaky += 1; print("FLAKY  %s  (its tests fail unmutated too: %s)" % (name, ", ".join(failing)))
        elif not passed:
            killed += 1; print("kill  %s  (%s)" % (name, ", ".join(failing)))
        else:
            survived += 1; print("SURVIVED  %s" % name)
        sys.stdout.flush()
    print("\n%d killed, %d survived, %d stale, %d skipped%s" % (killed, survived, stale, skipped,
                                                            ", %d flaky" % flaky if confirm else ""))
    shutil.rmtree(work)
    sys.exit(1 if survived or stale or skipped or flaky else 0)


main()
